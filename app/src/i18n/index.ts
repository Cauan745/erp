export type TranslationKey = keyof typeof ptBR;
export type Translator = (key: TranslationKey, params?: TranslationParams) => string;

function createTranslator(locale: Locale): Translator {
  const dictionary = locale === 'en' ? en : ptBR;

  return (key, params = {}) => {
    const value = dictionary[key] ?? ptBR[key];
    const text = typeof value === 'function' ? value(params) : value;
    return text.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(params[name] ?? ''));
  };
}

type I18nContextValue = {
  locale: Locale;
  t: Translator;
};

const I18nContext = createContext<I18nContextValue>({
  locale: 'pt-BR',
  t: createTranslator('pt-BR')
});

export function I18nProvider({ children, locale = 'pt-BR' }: { children: ReactNode; locale?: Locale }) {
  const value = useMemo(() => ({ locale, t: createTranslator(locale) }), [locale]);
  return createElement(I18nContext.Provider, { value, children });
}

export function useI18n() {
  return useContext(I18nContext);
}

export { createTranslator };
